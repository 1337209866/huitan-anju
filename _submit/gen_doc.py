# ===== 八、后续优化及推广设想 =====
h1('八、后续优化及推广设想')

body('当前版本用的是模拟数据，因为比赛环境下我们拿不到真实园区的电表读数。下一步最优先的工作是对接真实硬件——通过 Modbus 或者 MQTT 协议接入园区智能电表和空调机组控制器，让系统从"离线演示"变成"在线运行"。在数据量积累到三个月以上之后，我们还打算把现在的规则意图识别助手换成真正的大模型，让它能处理更复杂的追问，比如"为什么这个月 C 栋比 A 栋用电涨得快"这种需要跨模块关联分析的问题。')

body('在产品化层面，系统已经按配置文件驱动，换一个园区只需要修改 buildings 表里的面积、业态和参考单耗区间，不用重写算法。我们设想的推广路径是先在济南本地的保障房项目试点，跑通一个制冷季后再复制到其他园区。移动端方面，后续会做企业微信或钉钉小程序，把异常告警实时推送到运维人员手机上，发现异常后自动生成工单派给维修班组，形成"发现—派单—复核"的闭环。')

body('我们也清楚这个系统现在的局限：异常检测 F1 只有 0.335，距离工业级产品还有差距；对话助手目前是规则驱动，复杂问题处理不了；储能调度只考虑了峰谷套利，还没结合需求响应和需量管理。这些都是我们在后续迭代里要解决的问题，也是我们希望在决赛阶段继续打磨的方向。')

