# ===== 四、AI 在项目中的具体作用 =====
h1('四、AI 在项目中的具体作用')

body('我们在项目里刻意区分了"传统算法"和"AI"，避免把普通的数据处理包装成人工智能。AI 真正发挥作用的地方有三处。')

body('第一处是用机器学习做异常检测。我们最初试过 IsolationForest，也试过基于 EWMA 控制图的方法，但实际跑下来发现效果都不理想。IsolationForest 对渐变型异常特别不敏感——它擅长识别"突然冒出来的离群点"，但空调 COP 每天只衰减 0.4%，这种缓慢的漂移在特征空间里根本形不成孤立森林。EWMA 控制图在理论上很优美，但它假设残差方差稳定，而我们的数据里残差方差是异方差的：白天负荷高、波动大，深夜负荷低、波动小，直接套用理论方差会在深夜时段产生大量误报，我们第一次跑出来误报多达 2018 条，根本没法用。最后我们改用了工业 FDD（故障检测与诊断）领域更成熟的预测残差法：先用 LightGBM 学习一个"正常情况下每栋楼每小时应该用多少电"的模型，特征包括小时、工作日/周末、室外温度、前三个小时的温度加权值，唯独故意不引入滞后负荷项——因为一旦引入 lag 特征，模型就会跟着异常数据走，残差被抹平，渐变型异常就彻底漏检了。')

body('这里还有一个工程细节我们花了不少时间才解决。训练模型的时候，训练数据本身是带异常的，如果直接拿带异常的数据拟合，异常样本会把基线抬高，导致后面真正的异常反而过不了阈值。我们采用了两阶段鲁棒训练：先用全部数据拟合一次，算出残差的 MAD（中位数绝对偏差），把残差绝对值超过 2.5 倍 MAD 的疑似异常样本剔除，再用干净数据重新拟合一次。这样训练出来的"期望能耗"才是真正反映正常工况的基线。最终在 303 条人工标注的真实异常上，模型精确率 27.9%、召回率 41.9%、F1 为 0.335，而简单的 MAD 基线 F1 只有 0.151，提升了一倍多。我们没有追求更高的召回率——因为深夜基荷漂移这种异常，绝对偏移量只有一两千瓦，和噪声几乎同量级，硬要把它抓出来必然带来大量误报，反而让物业不敢看告警。')

body('第二处是用机器学习做未来 24 小时负荷预测。我们用 LightGBM 基于历史负荷和温度预测下一小时到未来 24 小时的负荷曲线，模型在留出测试集上 RMSE 约 4.5 千瓦。预测结果直接被储能调度模块使用——只有知道明天几点高峰、几点低谷，线性规划才能算出最优的充放电计划。')

body('第三处是自然语言对话入口。助手背后是一个轻量级的 Agent：先用规则识别用户问的是总览、楼栋、异常、预测、储能还是碳核算，然后调用对应的 Python 函数查数据库或跑算法，最后把真实数字填进自然语言模板返回。我们没有接外部大模型 API，因为比赛现场网络不一定稳定；但接口是预留好的，后续换成豆包或 DeepSeek 大模型时，工具层和数据层都不用动，只需要把模板生成替换成 LLM 生成即可。')

# ===== 五、核心工作流程和技术实现方式 =====
h1('五、核心工作流程和技术实现方式')

body('系统的技术栈很克制。后端用 Python 加 Flask，数据库用 SQLite——我们考虑过用 PostgreSQL，但对于一个三栋楼、90 天逐时数据（总共 6480 行）的规模，SQLite 足够，而且零配置，评委拿到代码双击就能跑。前端用原生 HTML/CSS/JavaScript 加 ECharts，不引入 React、Vue 这类重型框架，保证页面加载快、代码可读性高。算法层是四个独立模块：anomaly.py 做异常检测，forecast.py 做负荷预测，storage.py 用 PuLP 求解线性规划做储能调度，carbon.py 用排放因子法做碳核算。部署上用 Cloudflare Quick Tunnel 把本地 Flask 服务暴露成 HTTPS 公网地址，评委不需要下载任何代码就能在线体验。')

body('因为比赛没有提供真实的园区电表数据，我们自己写了一个数据生成器，按照真实建筑能耗规律模拟了 90 天的逐时数据。这个生成器不是简单地给一个基准值加随机噪声，而是尽量还原物理过程。用电负荷按建筑类型区分基准强度：办公楼全年约 100 千瓦时每平方米，住宅 35，商业 150，这个比例参考了《民用建筑能耗标准》。温度对负荷的影响不是瞬时的——建筑有热惯性，我们用前三个小时温度的加权平均来算空调负荷，权重分别是 0.5、0.3、0.2，这样中午 12 点的负荷不仅取决于当时的温度，也受上午 9 点、10 点、11 点温度的影响，更接近真实建筑的热过程。负荷噪声也不是纯白噪声，我们用了异方差加 AR(1) 自相关模型：白天波动大、深夜波动小，相邻小时的负荷有 0.7 的自相关系数，因为真实建筑里一小时的负荷不可能和前一小时毫无关系。')

img(os.path.join(IMG, 'bipv.jpg'), 13,
    '图 5：屋顶分布式光伏是保障房和产业园区常见配置，本系统已支持此类场景')

body('光伏模型用了马尔可夫天气链。每天的天气不是独立随机的，而是有持续性——晴天之后接着晴天的概率是 0.75，阴天之后接着阴天的概率也类似，这个转移矩阵是我们查了济南本地夏季的气象统计后设定的。在确定了晴/多云/阴天气之后，再按对应系数（晴天 0.75、多云 0.4、阴天 0.15）乘以装机容量得到逐时辐照，再叠加日内的云遮抖动。这样生成的光伏曲线，逐日总量的一阶自相关系数在 0.4 以上，说明天气是有记忆的，符合真实情况。')

body('最花心思的是异常注入。我们没有用"某一天突然加 80 千瓦"这种一眼就能看出来的假异常，而是设计了三类隐蔽异常。A 栋从第 65 天开始，空调系统 COP 每天衰减 0.4%，三个月下来累积衰减约 10%，表现为同温度下负荷缓慢爬升；B 栋在部分周末（我们选了第 0、4、17、18 个周末）晚上 20 点到 23 点忘记关空调，负荷比平时高 30%；C 栋从第 70 天开始深夜基荷每天漂移 0.4%，因为地下车库通风机老化或者公共照明没关。这三类异常分别对应工业现场的设备退化、人为疏忽和基荷漂移，用固定阈值法几乎抓不到，这也是我们为什么要上机器学习的原因。')

# ===== 六、项目当前完成情况及演示效果 =====
